async function loadNextCrucibleProblem(modality) {
  document.getElementById("b2-feedback").style.display = "none";
  try {
    const data = await fetchJson(`/api/block2/problem?puzzle_type=${encodeURIComponent(modality)}`);
    state.crucibleProblem = data.problem;
    state.crucibleState = data.crucible_state;
  } catch (_) {
    if (state.staticCrucibleBank && state.staticCrucibleBank[modality]) {
      const idx = Math.max(0, Math.min(4, (state.crucibleState.difficulty || 2) - 1));
      state.crucibleProblem = state.staticCrucibleBank[modality][idx];
    }
  }
  state.b2ProblemStartMs = Date.now();
  renderBlock2();
}

function renderBlock2() {
  const p = state.crucibleProblem;
  if (!p) return;

  document.getElementById("b2-difficulty-badge").textContent = `FLUID IQ • DYNAMIC DIFFICULTY LEVEL ${p.difficulty}/5 (${p.tier.toUpperCase()} TIER)`;
  document.getElementById("b2-problem-type-label").textContent = p.puzzle_type_label;
  document.getElementById("b2-streak-label").textContent = `Streak: ${state.crucibleState.streak} 🔥 | Level ${p.difficulty}/5`;
  document.getElementById("b2-problem-prompt").textContent = p.prompt;

  const stim = document.getElementById("b2-visual-stimulus");
  stim.innerHTML = "";

  if (p.puzzle_type === "matrix" && p.grid_svgs) {
    const grid = document.createElement("div");
    grid.className = "matrix-grid";
    p.grid_svgs.forEach((row) => {
      row.forEach((cellSvg) => {
        const cell = document.createElement("div");
        if (cellSvg === null) {
          cell.className = "matrix-cell missing";
          cell.textContent = "?";
        } else {
          cell.className = "matrix-cell";
          cell.innerHTML = cellSvg;
        }
        grid.appendChild(cell);
      });
    });
    stim.appendChild(grid);
  } else if (p.puzzle_type === "spatial" && p.reference_svg) {
    stim.innerHTML = `
      <div style="display:flex; flex-direction:column; align-items:center; margin:12px 0;">
        <span style="font-size:0.78rem; font-weight:700; color:var(--text-secondary); margin-bottom:6px;">REFERENCE CHIRAL POLYOMINO:</span>
        <div class="matrix-cell" style="width:104px; height:104px;">${p.reference_svg}</div>
      </div>
    `;
  }

  const optsContainer = document.getElementById("b2-options-container");
  optsContainer.innerHTML = "";

  if (p.options_are_svg) {
    const grid = document.createElement("div");
    grid.className = "svg-options-grid";
    p.options.forEach((svgStr, idx) => {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.className = "svg-choice-btn";
      btn.innerHTML = `<span style="font-size:0.75rem; font-weight:700;">Option ${String.fromCharCode(65 + idx)}</span>${svgStr}`;
      btn.addEventListener("click", () => submitCrucibleChoice(idx));
      grid.appendChild(btn);
    });
    optsContainer.appendChild(grid);
  } else {
    p.options.forEach((optText, idx) => {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.className = "option-label";
      btn.style.width = "100%";
      btn.style.textAlign = "left";
      btn.style.color = "var(--text-primary)";
      btn.innerHTML = `<strong>${String.fromCharCode(65 + idx)}.</strong> <span>${optText}</span>`;
      btn.addEventListener("click", () => submitCrucibleChoice(idx));
      optsContainer.appendChild(btn);
    });
  }
}

async function submitCrucibleChoice(chosenIdx) {
  const p = state.crucibleProblem;
  const isCorrect = chosenIdx === p.correct_index;
  const elapsedSec = Math.max(4, (Date.now() - state.b2ProblemStartMs) / 1000);

  const data = await fetchJson("/api/block2/submit", {
    method: "POST",
    body: JSON.stringify({
      puzzle_type: p.puzzle_type,
      difficulty: p.difficulty,
      is_correct: isCorrect,
      elapsed_sec: elapsedSec,
    }),
  });

  state.crucibleState = { difficulty: data.update.new_difficulty, streak: data.update.streak };
  state.schedule = data.schedule;
  state.benchmarks = data.benchmarks;
  renderSchedule();
  renderBenchmarks();

  const fb = document.getElementById("b2-feedback");
  fb.style.display = "block";
  fb.innerHTML = `
    <div>
      <strong>${isCorrect ? "✅ CORRECT DEDUCTION" : "❌ INCORRECT — OPTION " + String.fromCharCode(65 + p.correct_index) + " WAS CORRECT"}</strong>
      (Dynamic Difficulty scaled to <code>Level ${data.update.new_difficulty}/5</code> • Streak: <code>${data.update.streak}</code>)
    </div>
    <div style="margin-top:4px;">${p.explanation}</div>
  `;
}

