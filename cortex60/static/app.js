function fmtTime(sec) {
  const s = Math.max(0, Math.floor(sec));
  const m = Math.floor(s / 60);
  const rem = s % 60;
  return `${String(m).padStart(2, "0")}:${String(rem).padStart(2, "0")}`;
}

async function fetchJson(url, options = {}) {
  const res = await fetch(url, {
    headers: { "Content-Type": "application/json" },
    ...options,
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

async function initApp() {
  let data;
  try {
    data = await fetchJson("/api/bootstrap");
  } catch (_) {
    // Serverless GitHub Pages cloud fallback (loads pre-verified bundle generated by GitHub Actions)
    data = await fetchJson("./api_bootstrap.json");
    state.isStaticCloudMode = true;
    state.staticCrucibleBank = data.static_crucible_bank || null;
  }
  state.schedule = data.schedule;
  state.insights = data.insights;
  state.crucibleProblem = data.initial_crucible;
  state.crucibleState = data.crucible_state;
  state.mentalModels = data.mental_models;
  state.srsQueue = data.srs_queue;
  state.benchmarks = data.benchmarks;
  state.biometrics = data.biometrics;
  state.selectedBioDayIso = data.biometrics.today.day_iso;

  bindNavigation();
  bindBlock1();
  bindBlock2();
  bindBlock3();
  bindBlock4();
  bindBiometrics();

  renderSchedule();
  renderBlock1();
  renderBlock2();
  renderBlock3();
  renderBlock4();
  renderBenchmarks();
  renderBiometrics(true);
}

