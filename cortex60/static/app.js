function bindBiometrics() {
  const sleepEl = document.getElementById("switch-sleep");
  const actEl = document.getElementById("switch-activity");
  const nutEl = document.getElementById("switch-nutrition");

  const onSwitchChange = async () => {
    const targetDay = state.selectedBioDayIso || state.biometrics.today.day_iso;
    const data = await fetchJson("/api/biometrics/checkin", {
      method: "POST",
      body: JSON.stringify({
        day_iso: targetDay,
        sleep_quality: sleepEl.checked,
        physical_activity: actEl.checked,
        brain_nutrition: nutEl.checked,
      }),
    });
    state.biometrics = data.biometrics;
    renderBiometrics(true);
  };

  sleepEl.addEventListener("change", onSwitchChange);
  actEl.addEventListener("change", onSwitchChange);
  nutEl.addEventListener("change", onSwitchChange);

  document.getElementById("open-bio-toast-btn").addEventListener("click", () => {
    showBioPopoverToast();
  });
}

function showBioPopoverToast() {
  const toast = document.getElementById("bio-bottleneck-toast");
  if (toast && typeof toast.showPopover === "function") {
    try {
      toast.showPopover();
    } catch (_) {}
  }
}

function hideBioPopoverToast() {
  const toast = document.getElementById("bio-bottleneck-toast");
  if (toast && typeof toast.hidePopover === "function") {
    try {
      toast.hidePopover();
    } catch (_) {}
  }
}

function renderBiometrics(triggerToastIfLow = false) {
  if (!state.biometrics) return;
  const bio = state.biometrics;

  const selectedDay =
    bio.history_7days.find((d) => d.day_iso === state.selectedBioDayIso) || bio.today;

  document.getElementById("switch-sleep").checked = selectedDay.sleep_quality;
  document.getElementById("switch-activity").checked = selectedDay.physical_activity;
  document.getElementById("switch-nutrition").checked = selectedDay.brain_nutrition;

  const badge = document.getElementById("bio-compliance-badge");
  badge.textContent = `${bio.rolling_7day_compliance_pct}% (${bio.achieved_checks}/${bio.possible_checks})`;
  badge.className = `badge ${bio.bottleneck_alert_active ? "weak" : ""}`;

  const banner = document.getElementById("bio-system-banner");
  const titleEl = document.getElementById("bio-banner-title");
  const detailEl = document.getElementById("bio-banner-detail");

  if (bio.bottleneck_alert_active) {
    banner.classList.remove("optimal");
    titleEl.textContent = `🚨 BIOLOGICAL BOTTLENECK ALERT: 7-Day Compliance at ${bio.rolling_7day_compliance_pct}% (< 70% Required)`;
    detailEl.textContent =
      "System Warning: Cognitive gains in Fluid IQ and synaptic consolidation are currently being bottlenecked by physical biology. Complete today's check-in toggles to restore ≥70% neurogenesis compliance.";
    document.getElementById("toast-bio-body").textContent = bio.bottleneck_message;
    document.getElementById("toast-bio-lags").innerHTML = bio.lagging_vectors
      .map((l) => `<li>${l}</li>`)
      .join("");
    if (triggerToastIfLow) {
      showBioPopoverToast();
    }
  } else {
    banner.classList.add("optimal");
    titleEl.textContent = `✅ BIOLOGICAL PREREQUISITES OPTIMAL: 7-Day Compliance at ${bio.rolling_7day_compliance_pct}% (≥ 70%)`;
    detailEl.textContent =
      "Sleep architecture, aerobic BDNF upregulation, and Omega-3/hydration targets are actively supporting neurogenesis.";
    hideBioPopoverToast();
  }

  // Render 7-Day interactive history bar
  const grid = document.getElementById("bio-7day-grid");
  grid.innerHTML = "";
  bio.history_7days.forEach((day) => {
    const cell = document.createElement("button");
    cell.type = "button";
    const isSel = day.day_iso === selectedDay.day_iso;
    cell.style.padding = "6px 4px";
    cell.style.borderRadius = "6px";
    cell.style.cursor = "pointer";
    cell.style.border = isSel ? "2px solid var(--accent-primary)" : "1px solid var(--border-color)";
    cell.style.background = "var(--bg-elevated)";
    cell.style.color = "var(--text-primary)";
    cell.style.fontSize = "0.72rem";
    const shortDate = day.day_iso.slice(5);
    const icons = `${day.sleep_quality ? "🛌" : "·"}${day.physical_activity ? "🏃" : "·"}${day.brain_nutrition ? "🥑" : "·"}`;
    cell.innerHTML = `<div style="font-weight:700;">${day.is_today ? "TODAY" : shortDate}</div><div>${icons}</div>`;
    cell.addEventListener("click", () => {
      state.selectedBioDayIso = day.day_iso;
      renderBiometrics(false);
    });
    grid.appendChild(cell);
  });
}

