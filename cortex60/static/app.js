// BLOCK 1: THE INSIGHT ENGINE (10m Read + 5m Active Recall Constraint)
// ============================================================================
function bindBlock1() {
  const pullBtn = document.getElementById("b1-pull-live-btn");
  if (pullBtn) {
    pullBtn.addEventListener("click", async () => {
      pullBtn.disabled = true;
      pullBtn.textContent = "⏳ Verifying Live Sources...";
      try {
        const data = await fetchJson("/api/live-ingest?max_items=3", { method: "POST" });
        state.insights = data.insights;
        state.srsQueue = data.srs_queue;
        // Select the newly ingested live insight
        state.selectedInsightIdx = Math.max(0, state.insights.length - 1);
        renderBlock1();
        renderBlock4();
        pullBtn.textContent = `✅ Pulled ${data.ingested_count} Live Insights`;
      } catch (_) {
        pullBtn.textContent = "📡 Live Bundle Loaded (Cloud Cron)";
      } finally {
        pullBtn.disabled = false;
      }
    });
  }

  document.getElementById("b1-timer-toggle").addEventListener("click", () => {
    if (state.b1TimerId) {
      clearInterval(state.b1TimerId);
      state.b1TimerId = null;
      document.getElementById("b1-timer-toggle").textContent = "Resume Timer";
    } else {
      document.getElementById("b1-timer-toggle").textContent = "Pause Timer";
      state.b1TimerId = setInterval(() => {
        if (state.b1RemainingSec > 0) {
          state.b1RemainingSec--;
          if (state.b1Phase === "read") state.b1ReadElapsedSec++;
          document.getElementById("b1-time-str").textContent = fmtTime(state.b1RemainingSec);
        } else if (state.b1Phase === "read") {
          enterBlock1RecallPhase();
        }
      }, 1000);
    }
  });

  document.getElementById("b1-enter-recall-btn").addEventListener("click", () => {
    enterBlock1RecallPhase();
  });

  document.getElementById("b1-unlock-read-btn").addEventListener("click", () => {
    state.b1Phase = "read";
    document.getElementById("b1-article-body").classList.remove("locked-blur");
    document.getElementById("b1-recall-section").style.display = "none";
    document.getElementById("b1-enter-recall-btn").style.display = "inline-block";
    document.getElementById("b1-phase-label").textContent = "READ PHASE:";
  });

  document.getElementById("b1-submit-recall-btn").addEventListener("click", async () => {
    const concept = state.insights[state.selectedInsightIdx];
    const answers = concept.questions.map((_, qIdx) => {
      const checked = document.querySelector(`input[name="b1-q-${qIdx}"]:checked`);
      return checked ? Number(checked.value) : 0;
    });
    const readSecs = Math.max(95, state.b1ReadElapsedSec || 110);
    const data = await fetchJson("/api/block1/submit", {
      method: "POST",
      body: JSON.stringify({
        concept_id: concept.id,
        reading_seconds: readSecs,
        answers,
      }),
    });

    state.schedule = data.schedule;
    state.benchmarks = data.benchmarks;
    state.srsQueue = data.srs_queue;
    renderSchedule();
    renderBenchmarks();
    renderBlock4();

    const r = data.result;
    const fb = document.getElementById("b1-feedback");
    fb.style.display = "block";
    const lines = r.results
      .map(
        (item) =>
          `<div style="margin-top:6px;">${item.is_correct ? "✅" : "❌"} <strong>[${item.tier} Tier]:</strong> ${item.explanation}</div>`
      )
      .join("");
    fb.innerHTML = `
      <strong>📊 Active Recall Telemetry Recorded:</strong>
      Reading Comprehension Velocity: <code>${r.reading_wpm} WPM</code> | Accuracy: <code>${r.accuracy_pct}%</code> |
      Weak Concepts Flagged to Block 4 SRS: <code>${r.weak_flagged_count}</code>
      ${lines}
    `;
  });
}

