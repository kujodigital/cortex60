// NAVIGATION & MASTER 60-MINUTE SCHEDULE
// ============================================================================
function bindNavigation() {
  document.querySelectorAll(".block-tab").forEach((btn) => {
    btn.addEventListener("click", () => {
      const b = Number(btn.dataset.block);
      state.activeBlock = b;
      document.querySelectorAll(".block-tab").forEach((t) => t.classList.remove("active"));
      btn.classList.add("active");
      for (let i = 1; i <= 4; i++) {
        document.getElementById(`panel-block-${i}`).style.display = i === b ? "block" : "none";
      }
    });
  });
}

function renderSchedule() {
  if (!state.schedule) return;
  const s = state.schedule;
  const mins = Math.round(s.total_elapsed_seconds / 60);
  document.getElementById("master-budget-label").textContent = `${mins} / 60 mins (${s.total_progress_pct}%)`;
  document.getElementById("master-budget-fill").style.width = `${Math.min(100, s.total_progress_pct)}%`;

  for (let i = 1; i <= 4; i++) {
    const bInfo = s.blocks[`block${i}`];
    const bMins = Math.floor(bInfo.elapsed / 60);
    const icon = bInfo.done ? "✅" : "⏳";
    document.getElementById(`tab-b${i}-status`).textContent = `${icon} ${bMins}/15m`;
  }
}

