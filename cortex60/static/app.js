function renderBlock4() {
  const pills = document.getElementById("b4-queue-pills");
  pills.innerHTML = "";
  if (!state.srsQueue.length) return;
  if (state.selectedSrsIdx >= state.srsQueue.length) state.selectedSrsIdx = 0;

  state.srsQueue.forEach((card, idx) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = `pill-btn ${idx === state.selectedSrsIdx ? "active" : ""}`;
    const flag = card.is_weak ? "🚨 " : "";
    btn.textContent = `${flag}${idx + 1}. ${card.domain_or_model}`;
    btn.addEventListener("click", () => {
      state.selectedSrsIdx = idx;
      document.getElementById("b4-feedback").style.display = "none";
      renderBlock4();
    });
    pills.appendChild(btn);
  });

  const card = state.srsQueue[state.selectedSrsIdx];
  document.getElementById("b4-card-source").textContent = card.source_block.replace("_", " ");
  document.getElementById("b4-card-tier").textContent = `${card.tier} Tier`;
  document.getElementById("b4-card-weak-badge").style.display = card.is_weak ? "inline-flex" : "none";
  document.getElementById("b4-card-sm2-meta").textContent = `SM-2 Ease: ${card.ease_factor} • Interval: ${card.interval_days}d • Reps: ${card.repetitions}`;
  document.getElementById("b4-card-question").textContent = card.question;

  const opts = document.getElementById("b4-card-options");
  opts.innerHTML = "";
  card.options.forEach((optText, idx) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "option-label";
    btn.style.width = "100%";
    btn.style.textAlign = "left";
    btn.style.color = "var(--text-primary)";
    btn.innerHTML = `<strong>${String.fromCharCode(65 + idx)}.</strong> <span>${optText}</span>`;
    btn.addEventListener("click", () => submitSrsReview(card.card_id, idx));
    opts.appendChild(btn);
  });
}

async function submitSrsReview(cardId, chosenIdx) {
  const data = await fetchJson("/api/block4/review", {
    method: "POST",
    body: JSON.stringify({
      card_id: cardId,
      chosen_index: chosenIdx,
      confidence_grade: 4,
    }),
  });

  state.srsQueue = data.srs_queue;
  state.schedule = data.schedule;
  state.benchmarks = data.benchmarks;
  renderSchedule();
  renderBenchmarks();
  renderBlock4();

  const rev = data.review;
  const fb = document.getElementById("b4-feedback");
  fb.style.display = "block";
  fb.innerHTML = `
    <div>
      <strong>${rev.is_correct ? "✅ ACTIVE RECALL VERIFIED" : "❌ RECALL MISS — FLAGGED WEAK FOR PRIORITY RE-DRILL"}</strong>
      (New SM-2 Ease: <code>${rev.new_ease_factor}</code> • Next Interval: <code>${rev.new_interval_days} day(s)</code>)
    </div>
    <div style="margin-top:4px;">${rev.explanation}</div>
  `;
}

